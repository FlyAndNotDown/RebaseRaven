//! Workspace settings preserve server-managed and unexposed form fields.
use super::parse::{parse_ztag, set_spec_field, spec_field};
use super::review::{allow_empty, preview_reconcile, run, STALE};
use super::workspace::{connection_after_create, env_for, update_config_file, P4Connection};
use crate::error::{AppError, AppResult};
use serde::{Deserialize, Serialize};
use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct P4WorkspaceOptions {
    pub allwrite: bool,
    pub clobber: bool,
    pub compress: bool,
    pub modtime: bool,
    pub rmdir: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct P4WorkspaceEdit {
    pub root: String,
    pub view: Vec<String>,
    pub line_end: String,
    pub options: P4WorkspaceOptions,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct P4WorkspaceSettings {
    #[serde(flatten)]
    pub edit: P4WorkspaceEdit,
    pub stream: String,
    pub fingerprint: String,
}

pub(super) fn stable_spec(spec: &str) -> String {
    spec.lines()
        .filter(|line| !line.starts_with("Access:"))
        .collect::<Vec<_>>()
        .join("\n")
}

pub(super) fn block(spec: &str, field: &str) -> Vec<String> {
    let mut active = false;
    let mut lines = Vec::new();
    for line in spec.lines() {
        if line.starts_with(&format!("{field}:")) {
            active = true;
            continue;
        }
        if active && !line.is_empty() && !line.starts_with(char::is_whitespace) {
            break;
        }
        if active && !line.trim().is_empty() && !line.trim_start().starts_with('#') {
            lines.push(line.trim_start().to_string());
        }
    }
    lines
}

pub(super) fn set_block(spec: &str, field: &str, lines: &[String]) -> String {
    let mut result = String::new();
    let mut active = false;
    for line in spec.lines() {
        if line.starts_with(&format!("{field}:")) {
            active = true;
            continue;
        }
        if active && !line.is_empty() && !line.starts_with(char::is_whitespace) {
            active = false;
        }
        if !active {
            result.push_str(line);
            result.push('\n');
        }
    }
    result.push_str(&format!("{field}:\n"));
    for line in lines {
        result.push('\t');
        result.push_str(line);
        result.push('\n');
    }
    result
}

fn fingerprint(connection: &P4Connection, spec: &str) -> String {
    let mut hash = DefaultHasher::new();
    (
        &connection.port,
        &connection.user,
        &connection.client,
        stable_spec(spec),
    )
        .hash(&mut hash);
    format!("{:016x}", hash.finish())
}

fn settings(connection: &P4Connection, spec: &str) -> P4WorkspaceSettings {
    let options = spec_field(spec, "Options");
    let has = |flag| options.split_whitespace().any(|value| value == flag);
    P4WorkspaceSettings {
        edit: P4WorkspaceEdit {
            root: spec_field(spec, "Root"),
            view: block(spec, "View"),
            line_end: spec_field(spec, "LineEnd"),
            options: P4WorkspaceOptions {
                allwrite: has("allwrite"),
                clobber: has("clobber"),
                compress: has("compress"),
                modtime: has("modtime"),
                rmdir: has("rmdir"),
            },
        },
        stream: spec_field(spec, "Stream"),
        fingerprint: fingerprint(connection, spec),
    }
}

pub fn workspace_settings(connection: &P4Connection) -> AppResult<P4WorkspaceSettings> {
    let spec = run(connection, &["client", "-o", &connection.client])?;
    Ok(settings(connection, &spec))
}

fn edited_spec(spec: &str, edit: &P4WorkspaceEdit) -> AppResult<String> {
    if !Path::new(&edit.root).is_absolute() || edit.root.contains(['\0', '\r', '\n']) {
        return Err(AppError::msg(
            "Choose an absolute folder for the workspace.",
        ));
    }
    if !matches!(
        edit.line_end.as_str(),
        "local" | "unix" | "mac" | "win" | "share"
    ) {
        return Err(AppError::msg("Choose a supported line ending."));
    }
    let stream = spec_field(spec, "Stream");
    if !stream.is_empty() && edit.view != block(spec, "View") {
        return Err(AppError::msg(
            "Stream workspace mappings are generated by Perforce.",
        ));
    }
    if edit.view.is_empty()
        || edit.view.len() > 5000
        || edit.view.iter().any(|line| {
            line.contains(['\r', '\n', '\0'])
                || !line
                    .trim_start_matches(['-', '+', '&', '"'])
                    .starts_with("//")
        })
    {
        return Err(AppError::msg("Enter one valid workspace mapping per line."));
    }
    let old_options = spec_field(spec, "Options");
    let pairs = [
        ("allwrite", edit.options.allwrite),
        ("clobber", edit.options.clobber),
        ("compress", edit.options.compress),
        ("modtime", edit.options.modtime),
        ("rmdir", edit.options.rmdir),
    ];
    let mut options = old_options
        .split_whitespace()
        .filter(|word| {
            !pairs
                .iter()
                .any(|(name, _)| *word == *name || *word == format!("no{name}"))
        })
        .map(String::from)
        .collect::<Vec<_>>();
    options.extend(pairs.iter().map(|(name, enabled)| {
        if *enabled {
            name.to_string()
        } else {
            format!("no{name}")
        }
    }));
    let mut updated = set_spec_field(spec, "Root", &edit.root);
    updated = set_spec_field(&updated, "LineEnd", &edit.line_end);
    updated = set_spec_field(&updated, "Options", &options.join(" "));
    if stream.is_empty() {
        updated = set_block(&updated, "View", &edit.view);
    }
    Ok(updated)
}

pub fn save_workspace(
    connection: &P4Connection,
    edit: &P4WorkspaceEdit,
    expected: &str,
) -> AppResult<P4Connection> {
    let current = run(connection, &["client", "-o", &connection.client])?;
    if fingerprint(connection, &current) != expected {
        return Err(AppError::msg(STALE));
    }
    let updated = edited_spec(&current, edit)?;
    let moving = edit.root != spec_field(&current, "Root");
    if moving || edit.view != block(&current, "View") {
        let scope = format!("//{}/...", connection.client);
        let opened = allow_empty(run(connection, &["-ztag", "opened", &scope]))?;
        if !parse_ztag(&opened).is_empty() || !preview_reconcile(connection)?.files.is_empty() {
            return Err(AppError::msg("Submit, shelve and revert local changes before changing workspace mappings or root."));
        }
    }
    let root = PathBuf::from(&edit.root);
    std::fs::create_dir_all(&root)?;
    super::cli::run_p4_ok(&env_for(connection), &["client", "-i"], Some(&updated))?;
    let mut env = env_for(connection);
    env.cwd = root.clone();
    if moving {
        update_config_file(&root, &env)?;
    }
    connection_after_create(&env, &root, &spec_field(&updated, "Stream"))
}

#[cfg(test)]
mod tests {
    use super::*;
    const SPEC: &str = "Client: test\nRoot: /workspace\nAccess: yesterday\nOptions: noallwrite noclobber nocompress locked nomodtime normdir\nSubmitOptions: leaveunchanged\nLineEnd: local\nView:\n\t//depot/... //test/...\n\t-//depot/cache/... //test/cache/...\nChangeView:\n\t//depot/...@10\n";
    fn edit() -> P4WorkspaceEdit {
        P4WorkspaceEdit {
            root: std::env::temp_dir()
                .join("workspace")
                .to_string_lossy()
                .into_owned(),
            line_end: "unix".into(),
            view: vec!["//depot/project/... //test/project/...".into()],
            options: P4WorkspaceOptions {
                allwrite: true,
                clobber: false,
                compress: true,
                modtime: false,
                rmdir: true,
            },
        }
    }
    #[test]
    fn editing_mappings_and_options_preserves_other_fields() {
        let updated = edited_spec(SPEC, &edit()).unwrap();
        assert_eq!(block(&updated, "View"), edit().view);
        assert_eq!(block(&updated, "ChangeView"), vec!["//depot/...@10"]);
        assert_eq!(spec_field(&updated, "SubmitOptions"), "leaveunchanged");
        assert_eq!(
            spec_field(&updated, "Options"),
            "locked allwrite noclobber compress nomodtime rmdir"
        );
        assert_eq!(spec_field(&updated, "LineEnd"), "unix");
    }
    #[test]
    fn generated_views_and_form_injection_are_rejected() {
        assert!(edited_spec(&format!("{SPEC}Stream: //depot/main\n"), &edit()).is_err());
        let mut request = edit();
        request.root.push_str("\nHost: another");
        assert!(edited_spec(SPEC, &request).is_err());
        let mut request = edit();
        request.view[0].push_str("\nHost: another");
        assert!(edited_spec(SPEC, &request).is_err());
    }
}
